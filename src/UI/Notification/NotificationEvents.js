/**
 * 🎯 Unified Notification Events
 * 
 * Single source of truth for all notification events across the app.
 * Every event is defined here once, and used everywhere.
 * 
 * Usage:
 *   notify(NOTIFICATION_EVENTS.CHAT_MESSAGE, { ... })
 *   notify(NOTIFICATION_EVENTS.DEAL_CREATED, { ... })
 * 
 * Benefits:
 *   - Single source of truth
 *   - Easy to maintain
 *   - Auto-completion support
 *   - No typos
 *   - Centralized control
 *
 * ⚠️ IMPORTANT: Adding a key here is NOT enough to make notify() work.
 * You must ALSO add a matching entry in NotificationTemplates.js —
 * NotificationProvider.notify() looks up NotificationTemplates[event]
 * and silently no-ops (no sound, no Firestore write, nothing) if the
 * template is missing.
 *
 * ✅ NEW (this update) — added for the Deal Manager offer-expiry /
 * milestone-submission-review flow in DealManager.jsx:
 *   OFFER_EXPIRED, MILESTONE_SUBMITTED, MILESTONE_REJECTED,
 *   MILESTONE_REFUNDED
 * Remember to add matching templates for these four in
 * NotificationTemplates.js too, or notify() will silently no-op for them.
 */

