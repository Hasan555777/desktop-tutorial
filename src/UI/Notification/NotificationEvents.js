// 🎯 Helper Functions
// ============================================================

/**
 * Get event type (category)
 */
export const getEventType = (event) => {
  return NOTIFICATION_EVENT_TYPES[event] || NOTIFICATION_TYPES.SYSTEM;
};

/**
 * Get event priority
 */
export const getEventPriority = (event) => {
  return NOTIFICATION_EVENT_PRIORITIES[event] || NOTIFICATION_PRIORITIES.MEDIUM;
};

/**
 * Get event description
 */
export const getEventDescription = (event) => {
  return NOTIFICATION_EVENT_DESCRIPTIONS[event] || event;
};

/**
 * Check if event is high priority
 */
export const isHighPriority = (event) => {
  const priority = getEventPriority(event);
  return priority === NOTIFICATION_PRIORITIES.CRITICAL || 
         priority === NOTIFICATION_PRIORITIES.HIGH;
};

/**
 * Check if event exists
 */
export const isValidEvent = (event) => {
  return Object.values(NOTIFICATION_EVENTS).includes(event);
};

